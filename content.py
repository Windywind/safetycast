def holiday_name_for(date: datetime.date, upcoming_holidays):
    """根据即将到来的节假日日期列表，返回节假日名称（简单规则）。"""
    month = min(upcoming_holidays, default=None)
    if month is None:
        return "default"
    m = int(str(month)[5:7])
    if m in (1, 2):
        return "寒假"
    if m in (7, 8):
        return "暑假"
    return "default"


def get_daily_content(now: datetime.datetime) -> str:
    return DAILY_TEMPLATES.get(now.weekday(), DAILY_TEMPLATES[0])


def get_friday_content() -> str:
    return FRIDAY_TEMPLATE


def get_holiday_content(now: datetime.datetime, upcoming_holidays) -> str:
    name = holiday_name_for(now.date(), upcoming_holidays)
    return HOLIDAY_TEMPLATES.get(name, HOLIDAY_TEMPLATES["default"])
